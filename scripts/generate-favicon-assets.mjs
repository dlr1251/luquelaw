#!/usr/bin/env node
/**
 * Build Luque • Law favicon assets from Arbutus Slab (same display face as the site wordmark).
 * Run: node scripts/generate-favicon-assets.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontPath = join(root, "scripts/fonts/ArbutusSlab-Regular.ttf");
const viewSize = 128;
const forest = "#1c1f24";
const parchment = "#f5f6f7";
const gold = "#f0cd3a";
const leftText = "Luque";
const rightText = "Law";

const fontBytes = readFileSync(fontPath);
const font = opentype.parse(fontBytes);
const fontBase64 = fontBytes.toString("base64");

function layout(fontSize) {
  const gap = fontSize * 0.3;
  const dotR = fontSize * 0.25;
  const leftW = font.getAdvanceWidth(leftText, fontSize);
  const rightW = font.getAdvanceWidth(rightText, fontSize);
  const totalW = leftW + gap + dotR * 2 + gap + rightW;
  const ascender = (font.ascender / font.unitsPerEm) * fontSize;
  const descender = (font.descender / font.unitsPerEm) * fontSize;
  const textH = ascender - descender;
  const paddingX = (viewSize - totalW) / 2;
  const baselineY = (viewSize + textH) / 2 - descender;
  const dotCx = paddingX + leftW + gap + dotR;
  const dotCy = baselineY - ascender / 2;
  const rightX = paddingX + leftW + gap + dotR * 2 + gap;

  return {
    fontSize,
    totalW,
    paddingX,
    baselineY,
    rightX,
    dotCx,
    dotCy,
    dotR,
  };
}

let fontSize = 34;
let mark = layout(fontSize);
while (mark.totalW > viewSize - 10 && fontSize > 8) {
  fontSize -= 0.5;
  mark = layout(fontSize);
}

const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${viewSize}" height="${viewSize}" viewBox="0 0 ${viewSize} ${viewSize}">
  <defs>
    <style>
      @font-face {
        font-family: "Arbutus Slab";
        src: url("data:font/ttf;base64,${fontBase64}") format("truetype");
        font-weight: 400;
        font-style: normal;
      }
      .wordmark {
        font-family: "Arbutus Slab", Georgia, serif;
        font-size: ${mark.fontSize}px;
        font-weight: 400;
        fill: ${parchment};
      }
    </style>
  </defs>
  <rect width="${viewSize}" height="${viewSize}" fill="${forest}"/>
  <text class="wordmark" x="${mark.paddingX.toFixed(2)}" y="${mark.baselineY.toFixed(2)}">${leftText}</text>
  <circle cx="${mark.dotCx.toFixed(2)}" cy="${mark.dotCy.toFixed(2)}" r="${mark.dotR.toFixed(2)}" fill="${gold}"/>
  <text class="wordmark" x="${mark.rightX.toFixed(2)}" y="${mark.baselineY.toFixed(2)}">${rightText}</text>
</svg>
`;

const ts = `/** Generated by scripts/generate-favicon-assets.mjs — do not edit by hand. */

export const LL_MARK_VIEW_SIZE = ${viewSize};
export const LL_MARK_FONT_SIZE = ${mark.fontSize};
export const LL_MARK_LEFT = { text: ${JSON.stringify(leftText)}, x: ${mark.paddingX.toFixed(2)}, y: ${mark.baselineY.toFixed(2)} } as const;
export const LL_MARK_RIGHT = { text: ${JSON.stringify(rightText)}, x: ${mark.rightX.toFixed(2)}, y: ${mark.baselineY.toFixed(2)} } as const;
export const LL_MARK_DOT = { cx: ${mark.dotCx.toFixed(2)}, cy: ${mark.dotCy.toFixed(2)}, r: ${mark.dotR.toFixed(2)} } as const;
`;

writeFileSync(join(root, "public/favicon.svg"), svg);
mkdirSync(join(root, "src/lib/brand"), { recursive: true });
writeFileSync(join(root, "src/lib/brand/ll-mark.ts"), ts);
console.log(`wrote public/favicon.svg (Luque • Law, Arbutus Slab ${mark.fontSize}px)`);
console.log("wrote src/lib/brand/ll-mark.ts");

const outputs = [
  { size: 32, paths: ["src/app/icon.png", "public/favicon.png"] },
  { size: 180, paths: ["src/app/apple-icon.png"] },
  { size: 512, paths: ["public/icon-512.png"] },
];

for (const { size, paths } of outputs) {
  const png = await sharp(Buffer.from(svg)).resize(size, size).png().toBuffer();
  for (const rel of paths) {
    writeFileSync(join(root, rel), png);
    console.log(`wrote ${rel} (${size}px)`);
  }
}

function createIco(pngBuffers) {
  const count = pngBuffers.length;
  const headerSize = 6;
  const dirEntrySize = 16;
  const dataOffset = headerSize + dirEntrySize * count;
  let cursor = dataOffset;
  const entries = pngBuffers.map((buffer) => {
    const entry = { buffer, offset: cursor };
    cursor += buffer.length;
    return entry;
  });

  const ico = Buffer.alloc(cursor);
  ico.writeUInt16LE(0, 0);
  ico.writeUInt16LE(1, 2);
  ico.writeUInt16LE(count, 4);

  let dirPos = headerSize;
  for (const entry of entries) {
    const dimension = entry.buffer === pngBuffers[0] ? 16 : 32;
    ico.writeUInt8(dimension === 256 ? 0 : dimension, dirPos);
    ico.writeUInt8(dimension === 256 ? 0 : dimension, dirPos + 1);
    ico.writeUInt8(0, dirPos + 2);
    ico.writeUInt8(0, dirPos + 3);
    ico.writeUInt16LE(1, dirPos + 4);
    ico.writeUInt16LE(32, dirPos + 6);
    ico.writeUInt32LE(entry.buffer.length, dirPos + 8);
    ico.writeUInt32LE(entry.offset, dirPos + 12);
    dirPos += dirEntrySize;
  }

  for (const entry of entries) {
    entry.buffer.copy(ico, entry.offset);
  }

  return ico;
}

const png16 = await sharp(Buffer.from(svg)).resize(16, 16).png().toBuffer();
const png32 = await sharp(Buffer.from(svg)).resize(32, 32).png().toBuffer();
const ico = createIco([png16, png32]);

for (const rel of ["src/app/favicon.ico", "public/favicon.ico"]) {
  writeFileSync(join(root, rel), ico);
  console.log(`wrote ${rel}`);
}
